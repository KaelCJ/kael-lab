def definitions(hero, demon=False):
    palette = dict(PALETTES[hero])
    if demon: palette['skin']=['#797e99','#4c4d6c','#252b40']
    return '<defs>'+''.join(grad('d1-'+k,v) for k,v in palette.items())+'</defs>'

